-- Módulo Publicações: fila única de publicações do DJEN/Comunica PJe/e-mail.
-- Regra de escritório (02-publicacoes.md): a importação ALIMENTA A FILA e nunca cria prazo.
-- A criação de prazo exige leitura, classificação e confirmação expressa do advogado responsável.
-- Idempotente: pode ser executada quantas vezes for necessário.

CREATE TABLE IF NOT EXISTS public.publications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source TEXT NOT NULL DEFAULT 'DJEN',
  external_id TEXT,
  process_number TEXT,
  process_number_masked TEXT,
  process_id BIGINT REFERENCES public.processes(id) ON DELETE SET NULL,
  court TEXT,
  unit TEXT,
  publication_date DATE,
  page TEXT,
  communication_number BIGINT,
  chamber TEXT DEFAULT 'Judicial',
  importance TEXT,
  suggested_days INTEGER,
  content TEXT,
  link TEXT,
  document_type TEXT,
  communication_type TEXT,
  recipients JSONB DEFAULT '[]'::jsonb,
  status TEXT NOT NULL DEFAULT 'A triar',
  decision TEXT,
  decision_notes TEXT,
  responsible_id BIGINT REFERENCES public.lawyers(id) ON DELETE SET NULL,
  reviewed_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  reviewed_at TIMESTAMPTZ,
  read_at TIMESTAMPTZ,
  deadline_id BIGINT REFERENCES public.process_deadlines(id) ON DELETE SET NULL,
  environment TEXT NOT NULL DEFAULT 'production',
  synced_at TIMESTAMPTZ,
  raw_payload JSONB DEFAULT '{}'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Uma comunicação do DJEN é identificada de forma estável por (fonte, id externo, ambiente).
CREATE UNIQUE INDEX IF NOT EXISTS publications_source_external_env_key
  ON public.publications (source, external_id, environment);

CREATE INDEX IF NOT EXISTS publications_status_env_idx
  ON public.publications (status, environment);

CREATE INDEX IF NOT EXISTS publications_date_env_idx
  ON public.publications (publication_date DESC, environment);

CREATE INDEX IF NOT EXISTS publications_process_env_idx
  ON public.publications (process_id, environment);

CREATE INDEX IF NOT EXISTS publications_process_number_idx
  ON public.publications (process_number);

CREATE TABLE IF NOT EXISTS public.publication_sync_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sync_status TEXT NOT NULL DEFAULT 'Pendente',
  started_at TIMESTAMPTZ DEFAULT NOW(),
  finished_at TIMESTAMPTZ,
  date_start DATE,
  date_end DATE,
  tribunal TEXT,
  process_number TEXT,
  fetched_count INTEGER DEFAULT 0,
  inserted_count INTEGER DEFAULT 0,
  updated_count INTEGER DEFAULT 0,
  skipped_count INTEGER DEFAULT 0,
  pages_fetched INTEGER DEFAULT 0,
  error_message TEXT,
  environment TEXT NOT NULL DEFAULT 'production',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS publication_sync_log_env_date_idx
  ON public.publication_sync_log (environment, started_at DESC);

ALTER TABLE public.publications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.publication_sync_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all access to publications" ON public.publications;
CREATE POLICY "Allow all access to publications"
  ON public.publications FOR ALL
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all access to publication_sync_log" ON public.publication_sync_log;
CREATE POLICY "Allow all access to publication_sync_log"
  ON public.publication_sync_log FOR ALL
  USING (true) WITH CHECK (true);

GRANT ALL ON public.publications TO anon, authenticated, service_role;
GRANT ALL ON public.publication_sync_log TO anon, authenticated, service_role;

COMMENT ON TABLE public.publications IS
  'Fila de publicações (DJEN/Comunica PJe/e-mail). Importação não cria prazos automaticamente.';
COMMENT ON COLUMN public.publications.status IS
  'A triar, Triada, Ignorada ou Arquivada. Triagem é sempre humana.';
COMMENT ON COLUMN public.publications.deadline_id IS
  'Prazo criado somente após confirmação expressa do advogado responsável.';
COMMENT ON COLUMN public.publications.suggested_days IS
  'Sugestão automática de dias úteis; nunca substitui a confirmação do advogado.';
COMMENT ON COLUMN public.publication_sync_log.sync_status IS
  'Sincronizado, Erro ou Pendente.';
