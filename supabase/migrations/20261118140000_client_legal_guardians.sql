-- Representação legal de menores: o vínculo entre o menor e seu responsável
-- (pai, mãe, tutor ou curador) passa a ser um registro relacionado, e não um
-- nome gravado como texto em clients."legalRepresentative".
--
-- A coluna legada é preservada para não quebrar dados existentes. O backfill
-- é revisável pela interface; esta migration não cria clientes nem infere
-- vínculos automaticamente.

CREATE TABLE IF NOT EXISTS public.client_relationships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  environment TEXT NOT NULL DEFAULT 'production' CHECK (environment IN ('production', 'test')),
  client_id BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE CASCADE,
  related_client_id BIGINT NOT NULL REFERENCES public.clients(id) ON DELETE RESTRICT,
  relationship_type TEXT NOT NULL CHECK (relationship_type IN ('pai', 'mae', 'tutor', 'curador', 'outro')),
  relationship_label TEXT NOT NULL DEFAULT 'responsável legal',
  guardianship_type TEXT,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  valid_from DATE,
  valid_until DATE,
  created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT client_relationships_no_self CHECK (related_client_id <> client_id),
  CONSTRAINT client_relationships_unique UNIQUE (environment, client_id, related_client_id, relationship_type)
);

CREATE INDEX IF NOT EXISTS idx_client_relationships_client ON public.client_relationships(environment, client_id);
CREATE INDEX IF NOT EXISTS idx_client_relationships_related ON public.client_relationships(environment, related_client_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_client_relationships_primary
  ON public.client_relationships(environment, client_id) WHERE is_primary;

ALTER TABLE public.client_relationships ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Permissive access to client relationships" ON public.client_relationships;
CREATE POLICY "Permissive access to client relationships"
  ON public.client_relationships FOR ALL USING (true) WITH CHECK (true);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.client_relationships TO anon, authenticated, service_role;

-- Leitura achatada: menor + responsável. Usada pelo cadastro agora e pelo
-- catálogo de dados do módulo Documentos depois.
CREATE OR REPLACE VIEW public.v_client_guardians AS
SELECT
  r.id AS relationship_id,
  r.client_id,
  r.environment,
  r.related_client_id AS guardian_id,
  g.name AS guardian_name,
  g.document AS guardian_document,
  r.relationship_type,
  r.relationship_label,
  r.guardianship_type,
  r.is_primary,
  r.valid_from,
  r.valid_until
FROM public.client_relationships r
JOIN public.clients g ON g.id = r.related_client_id;

GRANT SELECT ON public.v_client_guardians TO anon, authenticated, service_role;

-- Substitui todos os vínculos de um menor em uma transação. Valida que o
-- menor e cada responsável pertençam ao mesmo ambiente da sessão.
CREATE OR REPLACE FUNCTION public.save_client_guardians(
  p_client_id BIGINT,
  p_environment TEXT,
  p_guardians JSONB DEFAULT '[]'::jsonb,
  p_edited_by BIGINT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY INVOKER
SET search_path = public
AS $$
DECLARE
  v_client_env TEXT;
  v_item JSONB;
  v_related BIGINT;
  v_primary_count INTEGER;
BEGIN
  IF p_client_id IS NULL OR NULLIF(BTRIM(COALESCE(p_environment, '')), '') IS NULL THEN
    RAISE EXCEPTION 'Cliente e ambiente são obrigatórios.' USING ERRCODE = '22023';
  END IF;

  SELECT environment INTO v_client_env FROM public.clients WHERE id = p_client_id;
  IF NOT FOUND OR v_client_env IS DISTINCT FROM p_environment THEN
    RAISE EXCEPTION 'Cliente não encontrado neste ambiente.' USING ERRCODE = 'P0002';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(COALESCE(p_guardians, '[]'::jsonb)) LOOP
    v_related := NULLIF(BTRIM(COALESCE(v_item->>'related_client_id', '')), '')::BIGINT;
    IF v_related IS NULL OR v_related = p_client_id THEN
      RAISE EXCEPTION 'Responsável inválido para o menor.' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM public.clients WHERE id = v_related AND environment = p_environment
    ) THEN
      RAISE EXCEPTION 'Responsável não encontrado neste ambiente.' USING ERRCODE = 'P0002';
    END IF;
  END LOOP;

  SELECT COUNT(*) INTO v_primary_count
  FROM jsonb_array_elements(COALESCE(p_guardians, '[]'::jsonb))
  WHERE COALESCE((value->>'is_primary')::BOOLEAN, FALSE);
  IF v_primary_count > 1 THEN
    RAISE EXCEPTION 'Apenas um responsável pode ser principal.' USING ERRCODE = '22023';
  END IF;

  DELETE FROM public.client_relationships
  WHERE client_id = p_client_id AND environment = p_environment;

  INSERT INTO public.client_relationships (
    environment, client_id, related_client_id, relationship_type,
    relationship_label, guardianship_type, is_primary, valid_from, valid_until,
    created_by, updated_by
  )
  SELECT
    p_environment,
    p_client_id,
    NULLIF(BTRIM(COALESCE(item->>'related_client_id', '')), '')::BIGINT,
    COALESCE(NULLIF(BTRIM(COALESCE(item->>'relationship_type', '')), ''), 'outro'),
    COALESCE(NULLIF(BTRIM(COALESCE(item->>'relationship_label', '')), ''), 'responsável legal'),
    NULLIF(BTRIM(COALESCE(item->>'guardianship_type', '')), ''),
    COALESCE((item->>'is_primary')::BOOLEAN, FALSE),
    NULLIF(BTRIM(COALESCE(item->>'valid_from', '')), '')::DATE,
    NULLIF(BTRIM(COALESCE(item->>'valid_until', '')), '')::DATE,
    p_edited_by,
    p_edited_by
  FROM jsonb_array_elements(COALESCE(p_guardians, '[]'::jsonb)) AS item;

  UPDATE public.clients
  SET updated_by = COALESCE(p_edited_by, updated_by)
  WHERE id = p_client_id;
END $$;

GRANT EXECUTE ON FUNCTION public.save_client_guardians(BIGINT, TEXT, JSONB, BIGINT)
  TO anon, authenticated, service_role;
