-- process_sync_status é uma VIEW calculada (não uma tabela), por isso não aceita
-- ADD COLUMN nem grava status real: tudo aparece como "Pendente".
-- Criamos uma tabela própria para registrar o resultado das sincronizações DataJud.

CREATE TABLE IF NOT EXISTS public.process_sync_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  process_id BIGINT NOT NULL,
  process_number TEXT,
  sync_status TEXT NOT NULL DEFAULT 'Pendente',
  last_sync TIMESTAMPTZ,
  error_message TEXT,
  environment TEXT DEFAULT 'production',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS process_sync_log_process_env_key
  ON public.process_sync_log (process_id, environment);

ALTER TABLE public.process_sync_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all access to process_sync_log" ON public.process_sync_log;
CREATE POLICY "Allow all access to process_sync_log"
  ON public.process_sync_log FOR ALL
  USING (true) WITH CHECK (true);

GRANT ALL ON public.process_sync_log TO anon, authenticated, service_role;

-- Corrige last_update gravado como o texto 'Agora' pelo antigo formulário,
-- que quebrava o cast para TIMESTAMPTZ em vw_process_velocity.
UPDATE public.processes
  SET last_update = CASE
    WHEN created_at IS NOT NULL THEN created_at::TEXT
    ELSE NULL
  END
  WHERE last_update = 'Agora';
