BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables
    WHERE pubname = 'supabase_realtime' AND schemaname = 'public' AND tablename = 'process_deadlines'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.process_deadlines;
  END IF;
END $$;

