-- Prazos editáveis: fonte única da verdade, auditoria e consistência entre
-- Processos, Prazos e Calendário. Todas as mutações passam pelas RPCs abaixo,
-- que gravam histórico e preservam os vínculos (publications.deadline_id).

-- Rastreabilidade das alterações (o log_audit_event() genérico já captura
-- old_data/new_data, mas não tinha responsável nem justificativa nos prazos).
ALTER TABLE public.process_deadlines
  ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS updated_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_process_deadlines_process ON public.process_deadlines(process_id);
CREATE INDEX IF NOT EXISTS idx_process_deadlines_env_date ON public.process_deadlines(environment, deadline_date);

CREATE TABLE IF NOT EXISTS public.process_deadline_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  deadline_id BIGINT NOT NULL,
  process_id BIGINT,
  environment TEXT NOT NULL DEFAULT 'production',
  action TEXT NOT NULL,
  old_data JSONB,
  new_data JSONB,
  changed_fields JSONB,
  justification TEXT,
  source TEXT,
  edited_by BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  edited_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_deadline_history_deadline ON public.process_deadline_history(deadline_id, edited_at DESC);
CREATE INDEX IF NOT EXISTS idx_deadline_history_env ON public.process_deadline_history(environment, edited_at DESC);

ALTER TABLE public.process_deadline_history ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Permissive read access for deadline history" ON public.process_deadline_history;
CREATE POLICY "Permissive read access for deadline history"
  ON public.process_deadline_history FOR ALL USING (true) WITH CHECK (true);

