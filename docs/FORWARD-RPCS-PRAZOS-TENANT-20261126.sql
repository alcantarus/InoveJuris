-- Resolucao interna da organizacao a partir do JWT assinado na camada 2.
create or replace function public._tenant_claim_organization_id()
returns uuid
language sql
stable
security definer
set search_path = public, extensions
as $$
  select nullif(current_setting('request.jwt.claims', true)::jsonb ->> 'organization_id', '')::uuid;
$$;

revoke all on function public._tenant_claim_organization_id() from public;
grant execute on function public._tenant_claim_organization_id() to anon, authenticated, service_role;

-- ---------------------------------------------------------------------------
-- create_process_deadline
-- ---------------------------------------------------------------------------
create or replace function public.create_process_deadline(
  p_process_id BIGINT,
  p_deadline_at TEXT,
  p_description TEXT,
  p_responsible_id BIGINT,
  p_business_days INTEGER,
  p_calculation_memory TEXT,
  p_environment TEXT,
  p_created_by BIGINT,
  p_source TEXT DEFAULT 'prazos'
)
returns public.process_deadlines
language plpgsql
security invoker
set search_path = public
set timezone = 'UTC'
as $$
declare
  v_org         uuid := public._tenant_claim_organization_id();
  v_process_env text;
  v_process_org uuid;
  v_at          timestamptz;
  v_new         public.process_deadlines;
begin
  if v_org is null then
    raise exception 'Organização da sessão não encontrada.' using errcode = '42501';
  end if;

  if p_process_id is null or nullif(btrim(coalesce(p_environment, '')), '') is null then
    raise exception 'Processo e ambiente são obrigatórios.' using errcode = '22023';
  end if;
  if nullif(btrim(coalesce(p_description, '')), '') is null then
    raise exception 'A descrição do prazo é obrigatória.' using errcode = '22023';
  end if;

  v_at := public.normalize_deadline_at(btrim(p_deadline_at));

  select environment, organization_id into v_process_env, v_process_org
    from public.processes
   where id = p_process_id;

  if not found
     or v_process_env is distinct from p_environment
     or v_process_org is distinct from v_org then
    raise exception 'Processo não encontrado neste ambiente/organização.' using errcode = 'P0002';
  end if;

  insert into public.process_deadlines (
    process_id, deadline_date, description, status, environment, organization_id,
    responsible_id, business_days, calculation_memory, created_by, updated_by
  ) values (
    p_process_id, v_at, btrim(p_description), 'Pendente', p_environment, v_org,
    p_responsible_id, p_business_days, nullif(btrim(coalesce(p_calculation_memory, '')), ''),
    p_created_by, p_created_by
  )
  returning * into v_new;

  insert into public.process_deadline_history (
    deadline_id, process_id, environment, action, new_data, justification, source, edited_by
  ) values (
    v_new.id, v_new.process_id, p_environment, 'criar', to_jsonb(v_new),
    'Prazo cadastrado.', nullif(btrim(coalesce(p_source, '')), ''), p_created_by
  );

  return v_new;
end $$;

-- ---------------------------------------------------------------------------
-- update_process_deadline
-- ---------------------------------------------------------------------------
create or replace function public.update_process_deadline(
  p_id BIGINT,
  p_environment TEXT,
  p_deadline_at TEXT,
  p_description TEXT,
  p_status TEXT,
  p_responsible_id BIGINT,
  p_justification TEXT,
  p_edited_by BIGINT,
  p_source TEXT DEFAULT 'prazos'
)
returns public.process_deadlines
language plpgsql
security invoker
set search_path = public
set timezone = 'UTC'
as $$
declare
  v_org         uuid := public._tenant_claim_organization_id();
  v_old         public.process_deadlines;
  v_new         public.process_deadlines;
  v_at          timestamptz;
  v_date_changed boolean;
  v_fields      jsonb;
begin
  if v_org is null then
    raise exception 'Organização da sessão não encontrada.' using errcode = '42501';
  end if;

  if p_id is null or nullif(btrim(coalesce(p_environment, '')), '') is null then
    raise exception 'Identificador e ambiente do prazo são obrigatórios.' using errcode = '22023';
  end if;
  if nullif(btrim(coalesce(p_description, '')), '') is null then
    raise exception 'A descrição do prazo é obrigatória.' using errcode = '22023';
  end if;

  v_at := public.normalize_deadline_at(btrim(p_deadline_at));

  select * into v_old
    from public.process_deadlines
   where id = p_id
     and environment = p_environment
     and organization_id = v_org
   for update;

  if not found then
    raise exception 'Prazo não encontrado neste ambiente/organização.' using errcode = 'P0002';
  end if;

  v_date_changed := v_old.deadline_date is distinct from v_at;

  if v_date_changed and nullif(btrim(coalesce(p_justification, '')), '') is null then
    raise exception 'Informe a justificativa para alterar a data do prazo.' using errcode = '22023';
  end if;

  update public.process_deadlines d
     set deadline_date = v_at,
         description = btrim(p_description),
         status = case when v_date_changed then 'Pendente' else coalesce(nullif(btrim(p_status), ''), d.status) end,
         responsible_id = coalesce(p_responsible_id, d.responsible_id),
         justification = case when v_date_changed then btrim(p_justification)
                              else coalesce(nullif(btrim(p_justification), ''), d.justification) end,
         confirmed_at = case when v_date_changed then null else d.confirmed_at end,
         confirmed_by = case when v_date_changed then null else d.confirmed_by end,
         updated_by = p_edited_by,
         updated_at = now()
   where d.id = p_id
     and d.environment = p_environment
     and d.organization_id = v_org
  returning * into v_new;

  select coalesce(jsonb_object_agg(key, value), '{}'::jsonb)
    into v_fields
    from jsonb_each(to_jsonb(v_new))
   where to_jsonb(v_old) -> key is distinct from value;

  insert into public.process_deadline_history (
    deadline_id, process_id, environment, action, old_data, new_data,
    changed_fields, justification, source, edited_by
  ) values (
    v_old.id, v_old.process_id, p_environment, 'editar',
    to_jsonb(v_old), to_jsonb(v_new), v_fields,
    nullif(btrim(coalesce(p_justification, '')), ''),
    nullif(btrim(coalesce(p_source, '')), ''), p_edited_by
  );

  return v_new;
end $$;

-- ---------------------------------------------------------------------------
-- confirm_process_deadline
-- ---------------------------------------------------------------------------
create or replace function public.confirm_process_deadline(
  p_id BIGINT,
  p_environment TEXT,
  p_edited_by BIGINT
)
returns public.process_deadlines
language plpgsql
security invoker
set search_path = public
set timezone = 'UTC'
as $$
declare
  v_org uuid := public._tenant_claim_organization_id();
  v_old public.process_deadlines;
  v_new public.process_deadlines;
begin
  if v_org is null then
    raise exception 'Organização da sessão não encontrada.' using errcode = '42501';
  end if;

  select * into v_old
    from public.process_deadlines
   where id = p_id
     and environment = p_environment
     and organization_id = v_org
   for update;

  if not found then
    raise exception 'Prazo não encontrado neste ambiente/organização.' using errcode = 'P0002';
  end if;

  update public.process_deadlines d
     set confirmed_at = now(),
         confirmed_by = p_edited_by,
         status = 'Confirmado',
         updated_by = p_edited_by,
         updated_at = now()
   where d.id = p_id
     and d.environment = p_environment
     and d.organization_id = v_org
  returning * into v_new;

  insert into public.process_deadline_history (
    deadline_id, process_id, environment, action, old_data, new_data, source, edited_by
  ) values (
    v_old.id, v_old.process_id, p_environment, 'confirmar',
    to_jsonb(v_old), to_jsonb(v_new), 'processo', p_edited_by
  );

  return v_new;
end $$;

-- ---------------------------------------------------------------------------
-- delete_process_deadline
-- ---------------------------------------------------------------------------
create or replace function public.delete_process_deadline(
  p_id BIGINT,
  p_environment TEXT,
  p_edited_by BIGINT,
  p_reason TEXT DEFAULT NULL,
  p_source TEXT DEFAULT 'processos'
)
returns boolean
language plpgsql
security invoker
set search_path = public
set timezone = 'UTC'
as $$
declare
  v_org uuid := public._tenant_claim_organization_id();
  v_old public.process_deadlines;
begin
  if v_org is null then
    raise exception 'Organização da sessão não encontrada.' using errcode = '42501';
  end if;

  select * into v_old
    from public.process_deadlines
   where id = p_id
     and environment = p_environment
     and organization_id = v_org
   for update;

  if not found then
    raise exception 'Prazo não encontrado neste ambiente/organização.' using errcode = 'P0002';
  end if;

  insert into public.process_deadline_history (
    deadline_id, process_id, environment, action, old_data, justification, source, edited_by
  ) values (
    v_old.id, v_old.process_id, p_environment, 'excluir', to_jsonb(v_old),
    nullif(btrim(coalesce(p_reason, '')), ''),
    nullif(btrim(coalesce(p_source, '')), ''), p_edited_by
  );

  delete from public.process_deadlines
   where id = p_id
     and environment = p_environment
     and organization_id = v_org;

  return true;
end $$;

commit;
